/// 屏幕传输线程。
///
/// * `snapshot` 给出当前配置和信箱里最新的一帧（`None` 表示没有新帧）。
/// * `publish` 把状态报给服务端（界面上的说明、预览图）。
///
/// 冷头没插、或者刚被控制循环重新打开时，这里什么都不做，等下一轮。
pub fn run(
    h2: &H2Slot,
    stop: &AtomicBool,
    snapshot: impl Fn() -> (Lcd, Option<Vec<u8>>),
    publish: impl Fn(LcdState),
) {
    let mut state = LcdState::default();
    // 已经初始化过的冷头代次：冷头重新打开（或推了灯圈）之后要重新初始化屏幕。
    let mut inited_gen: Option<u64> = None;
    // 已经下发的亮度 / 离线时钟。
    let mut applied: Option<(u8, bool)> = None;
    // 最近收到的一帧，冷头重新初始化后要重推它。
    let mut last_frame: Option<Vec<u8>> = None;
    // 已经推上屏幕的那一帧的摘要。
    let mut pushed: Option<u64> = None;
    // 上次推帧的时间：同一张画面也要隔一段时间重推。
    let mut pushed_at: Option<Instant> = None;

    while !stop.load(Ordering::SeqCst) {
        let (cfg, frame) = snapshot();
        if let Some(frame) = frame {
            last_frame = Some(frame);
        }

        if cfg.mode == LcdMode::Unmanaged {
            // 不托管：完全不碰屏幕，已经提交的画面也不推。
            if state.description != UNMANAGED {
                state = LcdState { description: UNMANAGED.into(), ..Default::default() };
                publish(state.clone());
            }
            inited_gen = None;
            applied = None;
            pushed = None;
            last_frame = None;
            std::thread::sleep(IDLE);
            continue;
        }

        let description = describe(&cfg, last_frame.is_some());
        if description != state.description {
            state.description = description;
            publish(state.clone());
        }

        let gen = h2.generation();
        let mut slot = h2.lock();
        let wait = match slot.as_mut() {
            // 冷头没接上：等控制循环重新打开。
            None => IDLE,
            Some(dev) => {
                let result = (|| -> anyhow::Result<()> {
                    if inited_gen != Some(gen) {
                        dev.lcd_init()?;
                        // 清掉 PNG 叠加层：L-Connect 主题的文字和仪表留在这层，会盖住我们的画面。
                        dev.push_png(TRANSPARENT_PNG)?;
                        inited_gen = Some(gen);
                        applied = None;
                        // 屏幕刚初始化过，之前那一帧要重推。
                        pushed = None;
                    }
                    if applied != Some((cfg.brightness, cfg.offline_clock)) {
                        dev.set_brightness(cfg.brightness)?;
                        dev.set_clock(if cfg.offline_clock { ClockMode::On } else { ClockMode::Off })?;
                        applied = Some((cfg.brightness, cfg.offline_clock));
                    }
                    if let Some(frame) = last_frame.as_ref() {
                        let digest = digest(frame);
                        // 换了画面就推；没换也要隔一段时间重推一次，
                        // 免得设备自己把屏幕切回它那一套。
                        let stale = pushed_at.is_none_or(|t| t.elapsed() >= STILL_REFRESH);
                        if pushed != Some(digest) || stale {
                            dev.push_jpeg(frame)?;
                            pushed = Some(digest);
                            pushed_at = Some(Instant::now());
                            state.preview = Some(frame.clone());
                            state.error = None;
                            publish(state.clone());
                        }
                    }
                    Ok(())
                })();
                match result {
                    Ok(()) => IDLE,
                    Err(e) => {
                        // 屏幕命令失败多半是冷头断开或卡住：交给控制循环重新打开。
                        let msg = format!("屏幕：{e:#}");
                        log::line(&msg);
                        state.error = Some(msg);
                        publish(state.clone());
                        *slot = None;
                        inited_gen = None;
                        pushed = None;
                        pushed_at = None;
                        IDLE
                    }
                }
            }
        };
        drop(slot);
        std::thread::sleep(wait);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use lcl_core::config::Lcd;

    #[test]
    fn describe_follows_the_config() {
        let mut cfg = Lcd { mode: LcdMode::Dashboard, theme: "ring".into(), ..Default::default() };
        assert_eq!(describe(&cfg, true), "主题：光环表盘");
        assert_eq!(describe(&cfg, false), "主题：光环表盘（等待内容宿主）");
        cfg.mode = LcdMode::Image;
        cfg.media_path = r"C:\壁纸\cat.png".into();
        assert_eq!(describe(&cfg, true), "图片：cat.png");
        cfg.mode = LcdMode::Gif;
        cfg.media_path = r"C:\壁纸\cat.gif".into();
        assert_eq!(describe(&cfg, true), "GIF：cat.gif");
        cfg.mode = LcdMode::Unmanaged;
        assert_eq!(describe(&cfg, true), UNMANAGED);
    }

    #[test]
    fn digest_separates_different_frames() {
        assert_eq!(digest(b"abc"), digest(b"abc"));
        assert_ne!(digest(b"abc"), digest(b"abd"));
        assert_ne!(digest(b"abc"), digest(b"ab"));
    }

    #[test]
    fn transparent_png_is_a_small_rgba_png() {
        // PNG 头、IHDR（480×480、8 位、颜色类型 6 = RGBA）、IEND。
        assert_eq!(&TRANSPARENT_PNG[..8], b"\x89PNG\r\n\x1a\n");
        assert_eq!(&TRANSPARENT_PNG[12..16], b"IHDR");
        assert_eq!(&TRANSPARENT_PNG[16..20], &[0x00, 0x00, 0x01, 0xe0]);
        assert_eq!(&TRANSPARENT_PNG[20..24], &[0x00, 0x00, 0x01, 0xe0]);
        assert_eq!(TRANSPARENT_PNG[24], 8, "位深");
        assert_eq!(TRANSPARENT_PNG[25], 6, "颜色类型必须是 RGBA");
        assert!(TRANSPARENT_PNG.len() < 4096, "透明 PNG 太大：{}", TRANSPARENT_PNG.len());
        assert_eq!(&TRANSPARENT_PNG[TRANSPARENT_PNG.len() - 8..TRANSPARENT_PNG.len() - 4], b"IEND");
    }
}
