//! 屏幕传输层：把内容宿主（`lcl-display-host`）提交的画面推到冷头屏幕上。
//!
//! 这一层只做传输：初始化屏幕、清掉 PNG 叠加层、亮度、离线时钟、推 JPEG。
//! 画面的解码、裁剪、旋转、仪表盘渲染都在内容宿主那边，守护进程不再读媒体文件，
//! 也不再依赖 `lcl-media`。
//!
//! 画面来源是 `Request::SubmitLcdFrame` 提交的 JPEG：服务端的信箱只留最新一帧，
//! 没有队列，宿主推得再快也不会堆积；这里也只推“和上次不是同一帧”的那张。
//!
//! H2 冷头（`0x1CBE:0xA034` 方屏 / `0x1CBE:0xA021` 圆屏）的 USB 句柄一直在
//! `H2Slot` 里，8.8 面板的直连接口（`0x1CBE:0xA088`，LP 那条路）和它的灯环
//! （`0x0416:0x8050`）都由守护进程直连：这个文件既不打开任何 USB，也不认领这些 PID。

use crate::h2slot::H2Slot;
use crate::log;
use lcl_core::config::{Lcd, LcdMode};
use lcl_devices::h2::ClockMode;
use std::path::Path;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::{Duration, Instant};

/// 没有新画面时的轮询间隔。
const IDLE: Duration = Duration::from_millis(100);
/// 同一张画面隔这么久重推一次，防止设备自己切回别的画面。
const STILL_REFRESH: Duration = Duration::from_secs(30);
/// “未控制”时的说明。
const UNMANAGED: &str = "未控制（保持设备现有画面）";

#[derive(Debug, Clone, Default)]
pub struct LcdState {
    pub description: String,
    pub error: Option<String>,
    /// 最近一次推到屏幕上的 JPEG。
    pub preview: Option<Vec<u8>>,
}

/// 屏幕当前显示什么的说明。守护进程只知道配置，不知道画面的细节，
/// 所以描述由配置推出来（主题名对 `lcl-media` 的 `THEMES`）。
fn describe(cfg: &Lcd, has_frame: bool) -> String {
    let base = match cfg.mode {
        LcdMode::Unmanaged => UNMANAGED.to_string(),
        LcdMode::Dashboard => format!("主题：{}", theme_name(&cfg.theme)),
        LcdMode::Image => format!("图片：{}", file_name(&cfg.media_path)),
        LcdMode::Gif => format!("GIF：{}", file_name(&cfg.media_path)),
    };
    if has_frame {
        base
    } else {
        format!("{base}（等待内容宿主）")
    }
}

/// 主题 id → 中文名。和 `lcl-media` 的 `theme::THEMES` 一一对应，改那边要改这里。
fn theme_name(id: &str) -> &str {
    match id {
        "swiss" => "瑞士网格",
        "line" => "单线",
        "block" => "色块海报",
        "tiles" => "数据卡片",
        "minimal" => "极简大字",
        "gauges" => "仪表组",
        "clock" => "时钟",
        "retro" => "复古液晶",
        "bars" => "柱状条",
        "ring" => "光环表盘",
        "glass" => "极光玻璃",
        "infinity" => "无限镜",
        "neon" => "霓虹",
        "liquid" => "液面",
        "radar" => "雷达",
        _ => id,
    }
}

/// 媒体路径里的文件名。
fn file_name(path: &str) -> String {
    Path::new(path)
        .file_name()
        .map_or_else(String::new, |n| n.to_string_lossy().into_owned())
}

/// 帧的摘要，用来判断“这一帧是不是已经推上去了”。
fn digest(bytes: &[u8]) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in bytes {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x100_0000_01b3);
    }
    h
}

